export function definitionIcon(name: string): LucideIcon {
  return ICON_MAP[name] ?? Square;
}

export function DefinitionIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Icon = definitionIcon(name);
  return <Icon className={className} aria-hidden="true" />;
}
